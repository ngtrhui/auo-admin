export const formatDate = (value: string) =>
  new Intl.DateTimeFormat("vi-VN", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(value));

export const getOrderTotal = (order: Order) =>
  order.items.reduce((total, item) => total + item.price * item.quantity, 0);
